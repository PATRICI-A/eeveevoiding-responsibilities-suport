package edu.eci.patricia.domain.model;

/**
 * Enumeration of inappropriate behavior report types available to students (RF24).
 */
public enum ReportType {

    /** Unwanted or offensive behavior of a personal, sexual, or aggressive nature. */
    HARASSMENT,

    /** Conduct that violates community standards or campus norms. */
    INAPPROPRIATE_BEHAVIOR,

    /** Content that is offensive, discriminatory, or harmful to others. */
    OFFENSIVE_CONTENT
}
